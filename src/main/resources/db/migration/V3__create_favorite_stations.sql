-- Per-user favorite stations. brand/addr/lat/lon are a snapshot taken when the station was starred,
-- so a favorite can still be shown/located when it is absent from the current /api/nearby answer.
CREATE TABLE favorite_stations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT           NOT NULL REFERENCES bot_users (user_id) ON DELETE CASCADE,
    osm_id     VARCHAR(64)      NOT NULL,
    brand      VARCHAR(255),
    addr       VARCHAR(512),
    lat        DOUBLE PRECISION NOT NULL,
    lon        DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMPTZ      NOT NULL,
    CONSTRAINT uq_favorite_stations_user_osm UNIQUE (user_id, osm_id)
);
